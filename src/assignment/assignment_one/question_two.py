"""
Question:2
Take two numbers as input from the user and print their sum, difference,
product, and quotient.
"""

number_one=int(input("Enter the first number: "))
number_two=int(input("Enter the second number: "))
sum_of_two=number_one+number_two
difference_of_two=number_one-number_two
product_of_two=number_one*number_two
quotient_of_two=number_one//number_two


print("sum:"+ str(sum_of_two))
print("difference:"+ str(difference_of_two))
print("product:"+ str(product_of_two))
print("quotient:"+ str(quotient_of_two))
